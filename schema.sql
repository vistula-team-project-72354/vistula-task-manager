begin;

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null check (length(btrim(title)) > 0),
  description text,
  completed boolean not null default false
);

alter table public.tasks enable row level security;
grant usage on schema public to anon;
grant select, insert, update, delete on table public.tasks to anon;
grant usage, select on sequence public.tasks_id_seq to anon;

drop policy if exists demo_tasks_select on public.tasks;
create policy demo_tasks_select on public.tasks for select to anon using (true);
drop policy if exists demo_tasks_insert on public.tasks;
create policy demo_tasks_insert on public.tasks for insert to anon with check (true);
drop policy if exists demo_tasks_update on public.tasks;
create policy demo_tasks_update on public.tasks for update to anon using (true) with check (true);
drop policy if exists demo_tasks_delete on public.tasks;
create policy demo_tasks_delete on public.tasks for delete to anon using (true);

commit;
